const PLACEHOLDERS = new Set(['random-secret-for-legacy-cookies', 'generate-a-random-key'])

/**
 * Require GLAS-injected service keys before the application starts.
 */
export function ensureAutoGeneratedCredentials(): void {
  if (process.env.NEXT_PHASE === 'phase-production-build') return

  if (process.env.NODE_ENV === 'test') {
    process.env.AUTH_SECRET ||= 'synthetic-auth-secret-for-tests-only'
    process.env.API_KEY ||= 'synthetic-api-key-for-tests-only'
    return
  }
  for (const name of ['AUTH_SECRET', 'API_KEY'] as const) {
    const value = (process.env[name] || '').trim()
    if (!value || PLACEHOLDERS.has(value)) {
      throw new Error(`${name} must be supplied by the Mission Control GLAS launch`)
    }
  }
}
