import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, expect, it } from 'vitest'
import { ensureAutoGeneratedCredentials } from '../auto-credentials'

const original = { ...process.env }
const cwd = process.cwd()

afterEach(() => {
  process.env = { ...original }
  process.chdir(cwd)
})

it('rejects an old persisted credential file when GLAS bindings are absent', () => {
  const directory = mkdtempSync(join(tmpdir(), 'mc-glas-credentials-'))
  try {
    mkdirSync(join(directory, '.data'))
    writeFileSync(join(directory, '.data', '.auto-generated'), 'AUTH_SECRET=old\nAPI_KEY=old\n')
    process.chdir(directory)
    process.env = { ...process.env, NODE_ENV: 'production' }
    delete process.env.NEXT_PHASE
    delete process.env.AUTH_SECRET
    delete process.env.API_KEY
    expect(() => ensureAutoGeneratedCredentials()).toThrow('AUTH_SECRET must be supplied')
  } finally {
    process.chdir(cwd)
    rmSync(directory, { recursive: true, force: true })
  }
})
